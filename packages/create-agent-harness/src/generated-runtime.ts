import { readFileSync } from 'node:fs';
import type { RenderedFile } from './walker.js';

/** Shared creation/upgrade overlay. Preserve project files; also emit plugin-root files. */
export function integrateGeneratedRuntime(files: RenderedFile[], name: string, claude: boolean): void {
  const put = (path: string, content: string) => {
    const old = files.find(f => f.path === path);
    if (old) old.content = content;
    else files.push({path, content, rendered: false, unresolved: []});
  };
  const pkgFile = files.find(f => f.path === 'package.json')!;
  const pkg = JSON.parse(pkgFile.content);
  // All scaffolds get an executable metadata server, never an npm-name placeholder.
  put('bin/mcp.js', readFileSync(new URL('../assets/generated-mcp.mjs', import.meta.url), 'utf8'));
  const cli = files.find(f => f.path === 'bin/cli.js');
  if (!cli || !cli.content.includes('switch (cmd) {')) {
    throw new Error('Generated CLI is missing its command dispatcher');
  }
  cli.content = cli.content.replace("switch (cmd) {", `switch (cmd) {
    case 'mcp': {
      if (!['start', 'index'].includes(argv[1]) || argv.length !== 2) {
        console.error('Usage: ${name} mcp start'); return 2;
      }
      const { startMcp } = await import('./mcp.js'); startMcp(); return undefined;
    }`)
    // An active stdio server must retain stdin; process.exit would close it immediately.
    .replace('.then((code) => process.exit(code))', '.then((code) => { if (code !== undefined) process.exitCode = code; })')
    .replace('  init     boot', '  mcp start  serve read-only harness metadata over stdio\\n  init     boot');

  if (claude) {
    const pluginFile = files.find(f => f.path === '.claude-plugin/plugin.json')!;
    const plugin = JSON.parse(pluginFile.content);
    plugin.author = {...plugin.author, name: plugin.author?.name ?? plugin.author?.displayName ?? 'Generated by metaharness'};
    plugin.mcpServers = {[name]: {command: 'node', args: ['${CLAUDE_PLUGIN_ROOT}/bin/mcp.js']}};
    put('.claude-plugin/plugin.json', JSON.stringify(plugin, null, 2) + '\n');
    // Plugin discovery uses these root directories; .claude/* remains project context.
    for (const file of [...files]) {
      if (/^\.claude\/(commands|skills)\//.test(file.path)) put(file.path.slice('.claude/'.length), file.content);
      const match = /^src\/agents\/([a-z0-9-]+)\.ts$/.exec(file.path);
      const prompt = /export const SYSTEM_PROMPT = `([\s\S]*?)`/.exec(file.content)?.[1];
      if (match && prompt) put(`agents/${match[1]}.md`, `---\nname: ${match[1]}\ndescription: ${JSON.stringify(`Project ${match[1]} for ${name}`)}\n---\n\n${prompt}\n`);
    }
    // Resolve relative commands from the project working directory for project mode.
    const settingsFile = files.find(f => f.path === '.claude/settings.json');
    if (settingsFile) {
      const settings = JSON.parse(settingsFile.content);
      const removedAliases: string[] = [];
      for (const [key, server] of Object.entries(settings.mcpServers ?? {})) {
        const entry = server as {command?: string; args?: string[]};
        if (entry.command === 'npx' && entry.args?.includes(`${name}@latest`)) {
          if (key === name) settings.mcpServers[key] = {command: 'node', args: ['./bin/mcp.js']};
          else {
            // Templates named nonexistent indexing/alerting services. Do not
            // register the metadata server under names suggesting those tools.
            delete settings.mcpServers[key]; removedAliases.push(key);
          }
        }
      }
      if (Array.isArray(settings.permissions?.allow)) {
        settings.permissions.allow = settings.permissions.allow.filter((rule: string) =>
          !removedAliases.some(alias => rule.startsWith(`mcp__${alias}__`)));
      }
      put('.claude/settings.json', JSON.stringify(settings, null, 2) + '\n');
    }
  }
  // Package only generated metadata, never mutable claims, sessions or key material.
  pkg.files = [...new Set([...(pkg.files ?? []), 'bin/**', '.claude-plugin/**',
    'commands/**', 'skills/**', 'agents/**', '.harness/manifest.json',
    '.harness/manifest.sha256', '.harness/mcp-policy.json'])];
  pkgFile.content = JSON.stringify(pkg, null, 2) + '\n';
}
