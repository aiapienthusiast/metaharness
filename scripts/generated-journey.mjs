// Installed-artifact acceptance, without host credentials or model calls.
// Run after npm run build: node scripts/generated-journey.mjs
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtempSync, writeFileSync, readFileSync, mkdirSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
const root = resolve('.');
const scratch = mkdtempSync(join(tmpdir(), 'metaharness installed journey '));
const run = (command, args, cwd = scratch) => execFileSync(command, args, {
  cwd, encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'],
  ...(process.platform === 'win32' && command === 'npm' ? {shell: true} : {}),
});
try {
  const tarballs = ['kernel-js', 'host-claude-code', 'create-agent-harness'].map(dir => {
    const [packed] = JSON.parse(run('npm', ['pack', '--json', '--ignore-scripts', '--pack-destination', scratch], join(root, 'packages', dir)));
    return join(scratch, packed.filename);
  });
  const consumer = join(scratch, 'consumer'); mkdirSync(consumer);
  writeFileSync(join(consumer, 'package.json'), '{"private":true,"type":"module"}\n');
  run('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund', ...tarballs], consumer);
  const installed = join(consumer, 'node_modules', 'metaharness', 'dist');
  run(process.execPath, [join(installed, 'bin.js'), 'new', 'journey-bot', '--template', 'vertical:coding', '--host', 'claude-code', '--no-darwin'], consumer);
  const harness = join(consumer, 'journey-bot');
  // Exercise the generated project's documented development commands as a user.
  run('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund'], harness);
  run('npm', ['run', 'build'], harness);
  const tests = run('npm', ['test', '--', '--run'], harness);
  assert.match(tests, /Tests\s+[1-9]\d* passed/);
  for (const command of ['init', 'doctor']) assert.match(run(process.execPath, ['bin/cli.js', command], harness), /kernel/);
  const doctor = run(process.execPath, [join(installed, 'harness-bin.js'), 'doctor', harness], consumer);
  assert.match(doctor, /HEALTHY/); assert.doesNotMatch(doctor, /--plugin-dir works/);
  const policyPath = join(harness, '.harness/mcp-policy.json');
  const policy = JSON.parse(readFileSync(policyPath)); policy.maxToolCallsPerTurn = 2;
  writeFileSync(policyPath, JSON.stringify(policy));
  run(process.execPath, [join(installed, 'harness-bin.js'), 'upgrade', harness, '--apply'], consumer);
  assert.equal(JSON.parse(readFileSync(policyPath)).maxToolCallsPerTurn, 2);
  const plugin = JSON.parse(readFileSync(join(harness, '.claude-plugin/plugin.json')));
  assert.equal(plugin.author.name, 'Generated by metaharness');
  // Runtime claims are private state and must not enter the published package.
  writeFileSync(join(harness, '.harness/claims.json'), '{"private":true}');
  const [packed] = JSON.parse(run('npm', ['pack', '--json', '--ignore-scripts', '--pack-destination', scratch], harness));
  const paths = packed.files.map(f => f.path);
  assert(!paths.includes('.harness/claims.json'));
  for (const path of ['.claude-plugin/plugin.json', 'commands/review-diff.md', 'skills/plan-change/SKILL.md', 'agents/reviewer.md', 'bin/mcp.js', '.harness/manifest.json', '.harness/manifest.sha256', '.harness/mcp-policy.json']) assert(paths.includes(path), path);
  // Install the generated package too, then run its bin and plugin MCP entry
  // from outside its source directory; workspace links cannot satisfy this check.
  run('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund', join(scratch, packed.filename)], consumer);
  const installedHarness = join(consumer, 'node_modules/journey-bot');
  assert.match(run(process.execPath, [join(installedHarness, 'bin/cli.js'), 'doctor'], consumer), /all checks passed/);
  assert.match(run(process.execPath, [join(installed, 'harness-bin.js'), 'doctor', installedHarness], consumer), /HEALTHY/);
  const server = JSON.parse(readFileSync(join(installedHarness, '.claude-plugin/plugin.json'))).mcpServers['journey-bot'];
  for (const args of [server.args.map(arg => arg.replace('${CLAUDE_PLUGIN_ROOT}', installedHarness)), [join(installedHarness, 'bin/cli.js'), 'mcp', 'start']]) {
    const client = new Client({name: 'installed-journey', version: '1.0.0'});
    try {
      await client.connect(new StdioClientTransport({command: process.execPath, args, cwd: consumer}));
      assert.deepEqual((await client.listTools()).tools.map(t => t.name), ['harness_info']);
      const result = await client.callTool({name: 'harness_info', arguments: {}});
      assert.notEqual(result.isError, true); assert.match(JSON.stringify(result.content), /journey-bot/);
    } finally { await client.close(); }
  }
  if (process.argv.includes('--claude-validate')) {
    // Explicit opt-in to an installed host's deterministic validator; no inference.
    assert.match(run('claude', ['plugin', 'validate', installedHarness], consumer), /Validation passed/i);
  }
  console.log('PASS installed generator -> scaffold -> install/build/test -> init/doctor -> policy-preserving upgrade -> generated tarball install -> plugin/CLI MCP initialize, list and call.');
} finally { rmSync(scratch, {recursive: true, force: true}); }
